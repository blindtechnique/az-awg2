#!/bin/bash
# Приёмка ask_yn: функция берётся из боевого install.sh, не переписывается.
SRC="${1:?путь к install.sh}"
fail=0
chk() { if [ "$2" = "$3" ]; then echo "  ✔ $1"; else echo "  ✘ $1 — ждали [$3], получили [$2]"; fail=1; fi; }

log() { :; }
has_tty() { return 0; }        # иначе awg3 сразу уходит в значение по умолчанию
# В тесте настоящего tty нет, поэтому ВСЕ обращения к нему разворачиваем на
# stdin/stderr: az-awg2 выбирает источник переменной src, awg3 читает /dev/tty
# напрямую. Не развернуть хотя бы одно — и функция повиснет на открытии.
eval "$(sed -n '/^ask_yn()/,/^}/p' "$SRC" \
        | sed -e 's#\[ -r /dev/tty \] && src=/dev/tty##' \
              -e 's#has_tty && src=/dev/tty##' \
              -e 's#src=/dev/tty#src=/dev/stdin#g' \
              -e 's#< /dev/tty#< /dev/stdin#g' \
              -e 's#> /dev/tty#>\&2#g')"

ans() {  # ans <что подать на вход> <значение по умолчанию>
    if printf "$1" | ask_yn "q: " "$2" 2>/dev/null; then echo ДА; else echo нет; fi
}

echo "── Обычные ответы ──────────────────────────────────────────────────────"
chk "y"        "$(ans 'y\n'   n)" "ДА"
chk "Y"        "$(ans 'Y\n'   n)" "ДА"
chk "yes"      "$(ans 'yes\n' n)" "ДА"
chk "да"       "$(ans 'да\n'  n)" "ДА"
chk "ДА"       "$(ans 'ДА\n'  n)" "ДА"
chk "n"        "$(ans 'n\n'   y)" "нет"
chk "нет"      "$(ans 'нет\n' y)" "нет"
chk "НЕТ"      "$(ans 'НЕТ\n' y)" "нет"

echo
echo "── Значение по умолчанию ───────────────────────────────────────────────"
chk "пустой ввод при def=y"  "$(ans '\n' y)" "ДА"
chk "пустой ввод при def=n"  "$(ans '\n' n)" "нет"
chk "EOF при def=y"          "$(ans ''   y)" "ДА"

echo
echo "── Тот самый случай: «н», backspace, «y» ───────────────────────────────"
# tty без IUTF8 стирает один байт из двухбайтовой «н» → остаётся \xd0, затем y
chk "хвост \\xd0 + y, следом переспрос и внятное y" "$(ans '\xd0y\ny\n' n)" "ДА"
echo "  (раньше этот ввод молча означал «нет» — бот не ставился)"
chk "хвост \\xd0 + y, следом n"                     "$(ans '\xd0y\nn\n' y)" "нет"

echo
echo "── Защита от вечного цикла ─────────────────────────────────────────────"
chk "пять мусорных ответов подряд → значение по умолчанию (y)" \
    "$(ans 'q\nw\ne\nr\nt\n' y)" "ДА"
chk "пять мусорных ответов подряд → значение по умолчанию (n)" \
    "$(ans 'q\nw\ne\nr\nt\n' n)" "нет"
chk "мусор, а затем EOF — не зависаем" "$(ans 'q\nw\n' n)" "нет"

echo
echo "── Опасные вопросы по-прежнему требуют явного «да» ─────────────────────"
chk "мусор при def=n не превращается в согласие" "$(ans 'zzz\nzzz\nzzz\nzzz\nzzz\n' n)" "нет"

echo
[ "$fail" = 0 ] && echo "═══ ВСЁ ЗЕЛЁНОЕ ═══" || echo "═══ ЕСТЬ ПАДЕНИЯ ═══"
exit $fail
