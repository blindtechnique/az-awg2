# regen-all: пропущенный сервис обязан быть слышен, а совет — вести туда, куда надо.
#
# Сервис без профиля пропускается намеренно — load_obfuscation завершается через
# die(), и без пропуска один сломанный сервис ронял бы пересборку конфигов у всех
# остальных. Но пропуск был молчаливым, а итог внизу печатал «переимпорт не
# нужен»: install.sh считал прогон удачным, бот отвечал успехом.
#
# Состояние, о котором речь, законного прочтения не имеет: слой включён,
# клиенты у него есть, профиля нет. Значит сервер уже на новом профиле, а эти
# конфиги остались на старом — и владелец узнаёт об этом от людей, которые
# перестали соединяться.
#
# Раздел 5 сторожит вторую половину. Сообщение появляется в аварийной ситуации,
# и владелец действует по написанному. Первая редакция советовала одну и ту же
# команду обоим слоям, а без --v3 обфускатор берёт профиль слоя 2.0: совет по
# поводу слоя 3.0 ЛОМАЛ исправный слой 2.0 — всем его клиентам пришлось бы
# раздавать конфиги заново, — и при этом слой 3.0 не чинил.
#
# Обратная сторона проверяется здесь же: там, где сказать нечего (клиентов нет,
# слой выключен, профиль на месте), не должно появиться ни строки — иначе вывод
# начнут пролистывать мимо той единственной, ради которой всё это.
#
#   bash tests/test_regen_skip.sh

fail=0
ROOT="$(cd "$(dirname "$(readlink -f "$0")")/.." && pwd)"
cd "$ROOT" || exit 1

SRC=overlay/bin/client-awg.sh
SVC=antizapret
SVC3=antizapret3
WORD=сервис

WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

ok()  { printf '  ✔ %s\n' "$1"; }
bad() { printf '  ✘ %s\n' "$1"; [ $# -gt 1 ] && printf '     %s\n' "$2"; fail=1; }
head_() { printf '\n\033[1m%s\033[0m\n' "$1"; }

RA="$(sed -n '/^regen_all()/,/^}$/p' "$SRC")"
if [ -z "$RA" ]; then
    echo "  ✘ не нашли regen_all в $SRC — мерить нечего"
    exit 1
fi

rc=0
run() {  # run <слой включён: 1|0> <профиль есть: 1|0> <сколько конфигов> [сервис]
    local on="$1" hasprof="$2" n="$3" svc="${4:-$SVC}"
    local d="$WORK/stand" i=1 l2=0 l3=0 prof=obfuscation.env
    rm -rf "$d"; mkdir -p "$d/awg" "$d/clients/$svc"
    if [ "$svc" = "$SVC3" ]; then
        l3="$on"; prof=obfuscation3.env
    else
        l2="$on"
    fi
    printf 'LAYER2=%s\nLAYER3=%s\n' "$l2" "$l3" > "$d/services.env"
    [ "$hasprof" = 1 ] && printf "AWG_Jc='4'\n" > "$d/awg/$prof"
    while [ "$i" -le "$n" ]; do
        printf '[Interface]\n' > "$d/clients/$svc/$svc-c$i-am.conf"
        i=$((i + 1))
    done
    local out
    # shellcheck disable=SC2034  # их читает вырезанная функция через eval
    out="$(
        set -euo pipefail
        SERVICES="$d/services.env"
        AWG_DIR="$d/awg"
        CLIENT_DIR="$d/clients"
        PY=true EXPORT=/dev/null AWG_OBFUSCATION=""
        log() { printf 'LOG %s\n' "$*"; }
        err() { printf 'ERR %s\n' "$*"; }
        resolve_service()  { printf 'ДОШЛИ %s\n' "$1"; }
        load_obfuscation() { :; }
        eval "$RA"
        regen_all 2>&1
    )"
    rc=$?
    printf '%s\n' "$out"
    # run зовут из подстановки команд, то есть из подоболочки: присваивание rc
    # наружу не выходит, и код приходится возвращать. Пока его возвращала
    # печать, раздел 2 был зелёным на непочиненном коде.
    return "$rc"
}

advice() {  # advice <вывод> → строка совета или пометка о её отсутствии
    printf '%s\n' "$1" | grep 'выпусти профиль' || echo "строки совета нет"
}

# ═══════════════════════════════════════════════════════════════════════════
head_ "1. Слой включён, клиенты есть, профиля нет — это слышно"
OUT="$(run 1 0 2)"; rc=$?
case "$OUT" in
    *"ERR $WORD $SVC ПРОПУЩЕН"*) ok "сказано, что сервис пропущен" ;;
    *) bad "пропуск молчаливый" "$OUT" ;;
esac
case "$OUT" in
    *"2 конфигов остались"*) ok "названо, сколько клиентов осталось на старом профиле" ;;
    *) bad "число не названо" "$OUT" ;;
esac
case "$OUT" in
    *"не соединятся"*) ok "и сказано, чем это кончится для них" ;;
    *) bad "последствие не названо" "$OUT" ;;
esac

# ═══════════════════════════════════════════════════════════════════════════
head_ "2. …и прогон не выдаёт себя за удачный"
[ "$rc" != 0 ] && ok "код возврата $rc" \
    || bad "код возврата 0" "install.sh и бот сообщат владельцу об успехе"
case "$OUT" in
    *"переимпорт не нужен"*) bad "итог всё равно обещает, что переимпорт не нужен" "$OUT" ;;
    *) ok "итог этого больше не обещает" ;;
esac

# ═══════════════════════════════════════════════════════════════════════════
head_ "3. Там, где сказать нечего, не сказано ничего"
OUT="$(run 1 0 0)"; rc=$?
case "$OUT" in
    *ПРОПУЩЕН*) bad "жалоба на сервис без клиентов" "$OUT" ;;
    *) ok "клиентов нет — пропуск беззвучен" ;;
esac
[ "$rc" = 0 ] && ok "и код нулевой" || bad "код $rc на пустом сервисе"

OUT="$(run 0 0 2)"; rc=$?
case "$OUT" in
    *ПРОПУЩЕН*) bad "жалоба на выключенный слой" "$OUT" ;;
    *) ok "слой выключен — не наше дело" ;;
esac
[ "$rc" = 0 ] && ok "и код нулевой" || bad "код $rc на выключенном слое"

# ═══════════════════════════════════════════════════════════════════════════
head_ "4. Профиль на месте — пропуска нет вовсе"
OUT="$(run 1 1 0)"; rc=$?
case "$OUT" in
    *"ДОШЛИ $SVC"*) ok "сервис дошёл до resolve_service" ;;
    *) bad "сервис не обработан, хотя профиль есть" "$OUT" ;;
esac
case "$OUT" in
    *ПРОПУЩЕН*) bad "пропуск при живом профиле" "$OUT" ;;
    *) ok "и ни слова о пропуске" ;;
esac
case "$OUT" in
    *"переимпорт не нужен"*) ok "итог как прежде" ;;
    *) bad "потерян обычный итог" "$OUT" ;;
esac
[ "$rc" = 0 ] && ok "код нулевой" || bad "код $rc при исправном сервисе"

# ═══════════════════════════════════════════════════════════════════════════
head_ "5. Совет ведёт к профилю ТОГО слоя, о котором жалоба"
# Ошибка здесь дороже молчания: владелец в аварии делает то, что написано, и
# командой без --v3 перевыпускает профиль слоя 2.0 поверх исправного слоя.
OUT="$(run 1 0 2 "$SVC")"
case "$OUT" in
    *"(awg-obfuscation --regenerate --apply)"*) ok "сервису слоя 2.0 — команда без --v3" ;;
    *) bad "сервису слоя 2.0 советуют не то" "$(advice "$OUT")" ;;
esac

OUT="$(run 1 0 2 "$SVC3")"
case "$OUT" in
    *"ERR $WORD $SVC3 ПРОПУЩЕН"*) ok "сервис слоя 3.0 тоже слышен" ;;
    *) bad "жалобы на сервис слоя 3.0 нет" "$OUT" ;;
esac
case "$OUT" in
    *"(awg-obfuscation --v3 --regenerate --apply)"*) ok "сервису слоя 3.0 — команда с --v3" ;;
    *) bad "сервису слоя 3.0 советуют команду без --v3" \
           "она перевыпустит профиль слоя 2.0 и сломает его клиентов, а слой 3.0 не починит: $(advice "$OUT")" ;;
esac

printf '\n'
[ "$fail" = 0 ] && echo "═══ ВСЁ ЗЕЛЁНОЕ ═══" || echo "═══ ЕСТЬ ПАДЕНИЯ ═══"
exit "$fail"
