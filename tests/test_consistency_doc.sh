#!/bin/bash
# SPDX-License-Identifier: GPL-3.0-or-later
# CONSISTENCY.md против кода — в ОБЕ стороны.
#
# Документ, описывающий модель, устаревает молча: это ровно та ложная зелень,
# против которой написана вся остальная диагностика. Поэтому он проверяется как
# код, и главное здесь — обратное направление.
#
#   вперёд:  каждая проверка, названная в таблице, существует в докторе
#            и хотя бы раз вызывается;
#   обратно: каждая проверка, которая в докторе есть, названа в таблице.
#
# Без обратного направления документ отстанет от кода и будет выглядеть полным.
#
#   bash tests/test_consistency_doc.sh
fail=0
ROOT="$(cd "$(dirname "$(readlink -f "$0")")/.." && pwd)"
cd "$ROOT" || exit 1

ok()  { printf '  ✔ %s\n' "$1"; }
bad() { printf '  ✘ %s\n' "$1"; [ $# -gt 1 ] && printf '     %s\n' "$2"; fail=1; }
head_() { printf '\n\033[1m%s\033[0m\n' "$1"; }

DOC=CONSISTENCY.md
CHK=overlay/bin/awg-doctor.sh
[ -f "$DOC" ] || { bad "нет $DOC" "модель не описана"; echo; exit 1; }

# Таблица размечена комментариями — так её границы не зависят от вёрстки
# соседнего текста.
table="$(sed -n '/CONSISTENCY-TABLE-START/,/CONSISTENCY-TABLE-END/p' "$DOC")"
[ -n "$table" ] || { bad "в $DOC нет размеченной таблицы" "мерить нечего"; echo; exit 1; }

# Имена проверок из четвёртой колонки, без разделителей и заголовка.
named="$(printf '%s\n' "$table" | awk -F'|' '/^\|/ {gsub(/[ `]/,"",$5); if ($5 ~ /^check_/) print $5}' | sort -u)"
# Все проверки, объявленные в докторе.
# Цифра в классе обязательна: без неё check_v3_stale режется на «check_v».
defined="$(grep -oE '^check_[a-z0-9_]+' "$CHK" | sort -u)"

# ═══════════════════════════════════════════════════════════════════════════
head_ "1. Каждая проверка из таблицы существует и вызывается"
n=0
for f in $named; do
    n=$((n + 1))
    if ! printf '%s\n' "$defined" | grep -qx "$f"; then
        bad "$f названа в $DOC, но её нет в $CHK" "документ описывает несуществующее"
        continue
    fi
    # Вызов, а не только объявление: проверка, которую не зовут, ничего не даёт.
    # Вызов может идти и без аргументов (check_marks, check_endpoint) —
    # тогда за именем сразу конец строки.
    if grep -qE "^ *$f( |\"|$)" "$CHK"; then
        ok "$f есть и вызывается"
    else
        bad "$f объявлена, но нигде не вызывается" "в документе она числится работающей"
    fi
done
[ "$n" != 0 ] && ok "проверок в таблице: $n" \
    || bad "в таблице нет ни одной проверки" "документ пуст по существу"

# ═══════════════════════════════════════════════════════════════════════════
head_ "2. Каждая проверка из доктора описана в таблице"
# Обратное направление — то, ради чего всё и затевалось: без него документ
# отстанет от кода незаметно и будет выглядеть полным.
# check_iface и check_endpoint описывают не копию значения, а состояние самой
# машины (поднят ли интерфейс, резолвится ли домен) — их перечисляем явно,
# чтобы исключение было видно, а не растворилось в шаблоне.
NOT_IN_TABLE="check_iface"
for f in $defined; do
    case " $NOT_IN_TABLE " in *" $f "*) continue ;; esac
    if printf '%s\n' "$named" | grep -qx "$f"; then
        ok "$f описана"
    else
        bad "$f есть в $CHK, но её нет в таблице $DOC" \
            "модель описывает меньше, чем проверяет код — документ устарел"
    fi
done

# ═══════════════════════════════════════════════════════════════════════════
head_ "3. Уровни в таблице — только из известного набора"
lv="$(printf '%s\n' "$table" | awk -F'|' '/^\|/ {gsub(/[ `]/,"",$6); if ($6 != "" && $6 != "уровень" && $6 !~ /^-+$/) print $6}' | sort -u)"
badlv=""
for l in $lv; do
    case "$l" in bad|warn|молчим) ;; *) badlv="$badlv $l" ;; esac
done
[ -z "$badlv" ] && ok "уровни: $(printf '%s' "$lv" | tr '\n' ' ')" \
    || bad "неизвестные уровни:$badlv" "набор уровней задан разделом «Как выбирается уровень»"

# ═══════════════════════════════════════════════════════════════════════════
head_ "4. Раздел про непокрытое не выброшен"
# Список того, что НЕ сверяется, — половина ценности документа: без него он
# читается как обещание полноты.
grep -q 'Чего эта модель не покрывает' "$DOC" \
    && ok "раздел о непокрытом на месте" \
    || bad "раздел о непокрытом исчез" "документ начинает читаться как обещание полноты"
grep -q 'сознательно не входит' "$DOC" \
    && ok "и раздел о сознательных исключениях" \
    || bad "исчезли сознательные исключения" "иначе их однажды добавят как «забытые»"

printf '\n'
[ "$fail" = 0 ] && echo "═══ ВСЁ ЗЕЛЁНОЕ ═══" || echo "═══ ЕСТЬ ПАДЕНИЯ ═══"
exit $fail
