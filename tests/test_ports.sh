#!/bin/bash
# SPDX-License-Identifier: GPL-3.0-or-later
# Инвариант портов: объявленный = записанный = тот, что у клиентов.
#
# Порт живёт в трёх местах сразу — в services.env, в серверном конфиге
# (ListenPort) и в каждом выданном клиенте (Endpoint). Разъехаться они могут
# молча: правка руками, оборванная миграция, перенос сервера. И тогда «порт не
# слушается» в диагностике — следствие, а не причина, а лечится расхождение
# переизданием клиентских конфигов, а не перезапуском сервиса.
#
# Функция вырезается из настоящего awg-doctor.sh и исполняется как есть.
#
#   bash tests/test_ports.sh
fail=0
ROOT="$(cd "$(dirname "$(readlink -f "$0")")/.." && pwd)"
cd "$ROOT" || exit 1

WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

ok()  { printf '  ✔ %s\n' "$1"; }
bad() { printf '  ✘ %s\n' "$1"; [ $# -gt 1 ] && printf '     %s\n' "$2"; fail=1; }
head_() { printf '\n\033[1m%s\033[0m\n' "$1"; }

DOC=overlay/bin/awg-doctor.sh
# check_ports зовёт valid_port и check_client_ports — режем все три, иначе
# кусок не самодостаточен.
FN="$(sed -n '/^valid_port()/,/^}$/p;/^check_client_ports()/,/^}$/p;/^check_ports()/,/^}$/p' "$DOC")"
[ -n "$FN" ] || { bad "не нашли check_ports в $DOC" "мерить нечего"; echo; exit 1; }

# ── стенд ───────────────────────────────────────────────────────────────────
mk() {  # mk <каталог> <порт сервера> <порт в конфиге> <порт у клиентов> <клиентов>
    local d="$1" srv="$3" cl="$4" n="$5" i
    rm -rf "$d"; mkdir -p "$d/etc" "$d/clients"
    printf '[Interface]\nPrivateKey = SRV\nListenPort = %s\n' "$srv" > "$d/etc/antizapret-awg.conf"
    for i in $(seq 1 "$n"); do
        printf '[Interface]\nPrivateKey = K%s\n\n[Peer]\nEndpoint = vpn.example.org:%s\n' \
            "$i" "$cl" > "$d/clients/antizapret-c$i-am.conf"
    done
}

run() {  # run <каталог> <объявленный порт> [строка в services.env]
    # Третий аргумент — что лежит в services.env: пусто значит «переменной там
    # нет вовсе». Доктор различает это и «переменная есть, но пуста»: первое
    # бывает на старой установке и доказать по нему нечего, второе — сломанный
    # план, при котором клиенты выписываются с негодным портом.
    # shellcheck disable=SC2034  # AWG_DIR и SERVICES читает вырезанная функция
    ( AWG_DIR="$1/etc"; SERVICES="$1/etc/services.env"
      : > "$SERVICES"
      [ -n "${3:-}" ] && printf '%s\n' "$3" > "$SERVICES"
      ok()   { printf 'OK %s\n' "$*"; }
      bad()  { printf 'BAD %s\n' "$*"; }
      warn() { printf 'WARN %s\n' "$*"; }
      eval "$FN"
      check_ports antizapret-awg "$2" "$1/clients" AZ_PORT )
}

# ═══════════════════════════════════════════════════════════════════════════
head_ "1. Всё согласовано — проверка молчит по существу"
D="$WORK/good"; mk "$D" 51820 51820 51820 3
out="$(run "$D" 51820)"
case "$out" in
    *"BAD"*) bad "исправное состояние названо поломкой" "$out" ;;
    *) ok "ни одной жалобы" ;;
esac
case "$out" in
    *"у всех 3 выданных конфигов Endpoint на порт 51820"*) ok "и сказано, сколько конфигов проверено" ;;
    *) bad "число проверенных конфигов не названо" "$out" ;;
esac

# ═══════════════════════════════════════════════════════════════════════════
head_ "2. Серверный конфиг разошёлся с services.env"
# Так выглядит правка ListenPort руками или оборванная миграция.
D="$WORK/srv"; mk "$D" 41111 41111 51820 2
out="$(run "$D" 51820)"
case "$out" in
    *"BAD antizapret-awg: в services.env порт 51820, в конфиге 41111"*) ok "расхождение названо числами" ;;
    *) bad "расхождение конфига не поймано" "$out" ;;
esac

# ═══════════════════════════════════════════════════════════════════════════
head_ "3. Клиентам роздан конфиг на старый порт"
# Самый неприятный случай: сервер в порядке, а выданные конфиги стучатся не
# туда. Перезапуск сервиса тут не поможет — нужно переиздание.
D="$WORK/cl"; mk "$D" 51820 51820 42222 4
out="$(run "$D" 51820)"
case "$out" in
    *"BAD antizapret-awg: у 4 из 4 конфигов Endpoint на чужой порт"*) ok "названы и число, и пример" ;;
    *) bad "чужой порт у клиентов не пойман" "$out" ;;
esac
case "$out" in
    *"42222"*) ok "и показано, какой именно порт стоит у клиента" ;;
    *) bad "чужой порт не показан" "$out" ;;
esac

# ═══════════════════════════════════════════════════════════════════════════
head_ "4. Частичное расхождение — считаются только несовпавшие"
D="$WORK/mix"; mk "$D" 51820 51820 51820 3
printf '[Interface]\nPrivateKey = KX\n\n[Peer]\nEndpoint = vpn.example.org:43333\n' \
    > "$D/clients/antizapret-old-am.conf"
out="$(run "$D" 51820)"
case "$out" in
    *"у 1 из 4 конфигов"*) ok "посчитан ровно один отставший из четырёх" ;;
    *) bad "счёт неверен" "$out" ;;
esac

# ═══════════════════════════════════════════════════════════════════════════
head_ "5. Переменной нет в services.env — сверять не с чем, и это не поломка"
D="$WORK/none"; mk "$D" 51820 51820 51820 1
out="$(run "$D" "")"
case "$out" in
    *"WARN порт antizapret-awg не объявлен"*) ok "сказано, что сверять не с чем" ;;
    *) bad "пустой порт не отличён от расхождения" "$out" ;;
esac
case "$out" in
    *BAD*) bad "названо поломкой" "на установке прежних версий переменной могло не быть" ;;
    *) ok "и это замечание, а не поломка" ;;
esac

# ═══════════════════════════════════════════════════════════════════════════
head_ "5б. Переменная есть, но пуста — вот это сломанный план"
# Слой объявлен включённым, порта у него нет. Клиенты при этом выписываются:
# слой 3.0 получит Endpoint на порт 0, а слой 2.0 в az — на 51443, ListenPort
# ВАНИЛЬНОГО wireguard. Второе глазом не заметить вовсе.
D="$WORK/empty"; mk "$D" 51820 51820 51820 1
out="$(run "$D" "" "AZ_PORT=''")"
case "$out" in
    *"BAD"*"пуст или недействителен"*) ok "пустое объявление названо поломкой" ;;
    *) bad "пустая переменная не отличена от отсутствующей" "$out" ;;
esac

# ═══════════════════════════════════════════════════════════════════════════
head_ "5в. Недействительный порт у клиента виден и без объявленного"
# Раньше ранний выход выключал осмотр клиентов ровно здесь — то есть там, где
# поломка гарантирована. Порт вне 1..65535 доказывается ОДНИМ файлом.
D="$WORK/zero"; mk "$D" 51820 51820 0 2
out="$(run "$D" "")"
case "$out" in
    *"BAD"*"недействительный порт"*) ok "негодный порт у клиентов найден" ;;
    *) bad "порт 0 в Endpoint пропущен" "$out" ;;
esac
case "$out" in
    *"из 2 конфигов"*) ok "и посчитаны оба" ;;
    *) bad "число не названо" "$out" ;;
esac

# ═══════════════════════════════════════════════════════════════════════════
head_ "5г. Годный порт у клиентов при пустом объявлении не оговаривается"
D="$WORK/ok"; mk "$D" 51820 51820 51820 2
out="$(run "$D" "")"
case "$out" in
    *"недействительный порт"*) bad "жалоба на исправные конфиги" "$out" ;;
    *) ok "к самим конфигам претензий нет" ;;
esac

# ═══════════════════════════════════════════════════════════════════════════
head_ "6. Конфиг без ListenPort"
D="$WORK/nolp"; mk "$D" 51820 51820 51820 1
printf '[Interface]\nPrivateKey = SRV\n' > "$D/etc/antizapret-awg.conf"
out="$(run "$D" 51820)"
case "$out" in
    *"нет ListenPort"*) ok "отсутствие порта в конфиге названо прямо" ;;
    *) bad "конфиг без ListenPort не пойман" "$out" ;;
esac

printf '\n'
[ "$fail" = 0 ] && echo "═══ ВСЁ ЗЕЛЁНОЕ ═══" || echo "═══ ЕСТЬ ПАДЕНИЯ ═══"
exit $fail
