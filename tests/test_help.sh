#!/bin/bash
# SPDX-License-Identifier: GPL-3.0-or-later
# --help печатает справку, а не все комментарии файла.
#
# Было два способа испортить это, и оба были в дереве:
#
#   * `grep '^#' "$0"` берёт КАЖДУЮ строку с решётки — шапку, разделители
#     «# ════…» и заметки для читателя кода, в том числе о неисправленных
#     дефектах апстрима. У install.sh это 185 строк вместо 63, и первой шла
#     «!/usr/bin/env bash»: sed срезал решётку у шебанга;
#   * `sed -n '3,15p'` не знает, где шапка кончилась. Все пять таких диапазонов
#     заезжали за её конец и печатали первую строку кода; стоило бы шапке
#     подрасти — справка молча обрезалась бы. Ошибка тихая в обе стороны.
#
# Отдельно: справка обязана работать ТАМ, ГДЕ ЕЁ ЧИТАЮТ — на чистой машине,
# не из-под root и до установки сервера. Именно тогда она нужнее всего, и
# именно там её терял соседний репозиторий: проверки прав и services.env
# стояли раньше разбора аргументов.
#
# Проверка сравнивает вывод с шапкой, посчитанной ДРУГИМ способом (диапазон
# строк вместо потоковой обработки): совпадающая реализация проверяла бы сама
# себя. Плюс отрицательная сторона — последняя строка-комментарий файла лежит
# заведомо ниже шапки и в справку попадать не должна.
#
#   bash tests/test_help.sh

fail=0
ROOT="$(cd "$(dirname "$(readlink -f "$0")")/.." && pwd)"
cd "$ROOT" || exit 1

ok()  { printf '  ✔ %s\n' "$1"; }
bad() { printf '  ✘ %s\n' "$1"; [ $# -gt 1 ] && printf '     %s\n' "$2"; fail=1; }
head_() { printf '\n\033[1m%s\033[0m\n' "$1"; }

SCRIPTS="install.sh
overlay/bin/awg-backup.sh
overlay/bin/awg-doctor.sh
overlay/bin/awg-obfuscation.sh
overlay/bin/awg-upstream-check.sh
overlay/bin/client-awg.sh"

WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

# ═══════════════════════════════════════════════════════════════════════════
head_ "1. Каждый --help печатает ровно шапку своего файла"
for f in $SCRIPTS; do
    [ -f "$f" ] || { bad "нет файла $f" "список в тесте разошёлся с деревом"; continue; }
    base="$(basename "$f")"

    # Шапка: от второй строки до первой строки без решётки, без маркера
    # лицензии. Считается диапазоном — намеренно не тем способом, каким её
    # печатает сам скрипт.
    end="$(awk 'NR>1 && !/^#/ {print NR; exit}' "$f")"
    if [ -z "$end" ] || [ "$end" -lt 3 ]; then
        bad "$base: не нашли конец шапки" "файл целиком из комментариев?"
        continue
    fi
    sed -n "2,$((end - 1))p" "$f" | grep -v '^# *SPDX-' | sed 's/^# \?//' > "$WORK/want"

    if ! timeout 30 bash "$f" --help > "$WORK/got" 2>"$WORK/err"; then
        bad "$base: --help вышел с ненулевым кодом" "$(head -2 "$WORK/err")"
        continue
    fi

    if cmp -s "$WORK/want" "$WORK/got"; then
        ok "$base — совпало со шапкой ($(wc -l < "$WORK/got") строк)"
    else
        bad "$base: справка не равна шапке" \
            "шапка $(wc -l < "$WORK/want") строк, справка $(wc -l < "$WORK/got"); первая разница: $(diff "$WORK/want" "$WORK/got" | head -2 | tr '\n' ' ')"
    fi

    # Отрицательная сторона: последняя строка-комментарий файла лежит заведомо
    # ниже шапки. Если она в выводе — печатается весь файл, а не справка.
    low="$(grep '^#' "$f" | tail -1 | sed 's/^# \?//')"
    if [ -n "$low" ] && grep -qF -- "$low" "$WORK/got"; then
        bad "$base: в справку попал комментарий из тела файла" "«$low»"
    fi

    case "$(head -1 "$WORK/got")" in
        "$base"*) ;;
        '!'*) bad "$base: справка начинается с обрубленного шебанга" "$(head -1 "$WORK/got")" ;;
        *)    bad "$base: справка начинается не с имени скрипта" "$(head -1 "$WORK/got")" ;;
    esac
    grep -q 'SPDX' "$WORK/got" && bad "$base: в справке маркер лицензии" "это не справка, а заголовок файла"
done

# ═══════════════════════════════════════════════════════════════════════════
head_ "2. Справка работает там, где её читают"
# На чистой машине (не root, сервер не установлен) она нужнее всего — и именно
# там её не было: проверки стояли раньше разбора аргументов.
if [ "$(id -u)" = 0 ]; then
    printf '  · прогон из-под root: «без прав» проверить нечем\n'
else
    for f in overlay/bin/client-awg.sh overlay/bin/awg-doctor.sh; do
        [ -f "$f" ] || continue
        if timeout 30 bash "$f" --help >/dev/null 2>"$WORK/err2"; then
            ok "$(basename "$f") отдаёт справку без root и без services.env"
        else
            bad "$(basename "$f"): справки нет на чистой машине" "$(head -1 "$WORK/err2")"
        fi
    done
fi

# ═══════════════════════════════════════════════════════════════════════════
head_ "3. Список в тесте не отстал от дерева"
# Иначе новый скрипт со сломанной справкой просто не попадёт в проверку, и она
# останется зелёной — молча.
miss=""
while IFS= read -r f; do
    case "$f" in tests/*) continue ;; esac
    grep -q 'sub(/\^# ?/' "$f" || continue
    printf '%s\n' "$SCRIPTS" | grep -qx -- "$f" || miss="$miss $f"
done < <(git ls-files '*.sh' 2>/dev/null)
[ -z "$miss" ] && ok "все скрипты со справкой перечислены" \
    || bad "в тесте нет:$miss" "их справка не проверяется вовсе"

# И обратная сторона: кто предлагает --help, обязан печатать её общим правилом,
# а не своим. Жёсткие диапазоны строк уже один раз разъехались с шапкой.
odd=""
while IFS= read -r f; do
    case "$f" in tests/*) continue ;; esac
    grep -q -- '-h|--help)' "$f" || continue
    grep -q 'sub(/\^# ?/' "$f" || odd="$odd $f"
done < <(git ls-files '*.sh' 2>/dev/null)
[ -z "$odd" ] && ok "и печатают её одним общим правилом" \
    || bad "печатают справку по-своему:$odd" "жёсткие диапазоны молча расходятся с шапкой"

printf '\n'
[ "$fail" = 0 ] && echo "═══ ВСЁ ЗЕЛЁНОЕ ═══" || echo "═══ ЕСТЬ ПАДЕНИЯ ═══"
exit "$fail"
