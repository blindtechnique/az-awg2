# DNS-view для подсетей слоя: пишутся в том формате, в каком их пишет ваниль.
#
# Прежняя редакция была написана против ВЫДУМАННОГО формата. Ваниль пишет
# сетевой адрес:
#
#   view:addr('10.29.8.0/24', policy.domains(policy.ANSWER(
#       {[kres.type.A] = {rdata = kres.str2ip('10.29.8.1'), ttl = min_ttl}}),
#       {todname(hostname())}))
#
# а скрипт искал, вставлял и якорился на форму с адресом ШЛЮЗА —
# `view:addr('10.29.9.1/24'`. Такой строки у ванили не бывает ни разу, поэтому
# якорь не совпадал НИКОГДА: функция возвращала None, скрипт выходил с нулём и
# не печатал ничего, а оба вызова в интеграции глушили и вывод, и код возврата.
#
# Доктор искал ту же несуществующую форму, поэтому жёлтое «не хватает view»
# горело на каждом исправном сервере, включая только что установленный. Ошибка
# была одна, а выглядела как две разные.
#
# Образец kresd.conf здесь — дословно с настоящего сервера, включая соседние
# view ванили. Проверка на выдуманном образце и была первопричиной.
#
#   bash tests/test_knot_view.sh

fail=0
ROOT="$(cd "$(dirname "$(readlink -f "$0")")/.." && pwd)"
cd "$ROOT" || exit 1

WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

ok()  { printf '  ✔ %s\n' "$1"; }
bad() { printf '  ✘ %s\n' "$1"; [ $# -gt 1 ] && printf '     %s\n' "$2"; fail=1; }
head_() { printf '\n\033[1m%s\033[0m\n' "$1"; }

SH=overlay/bin/awg-knot-view.sh
[ -f "$SH" ] || { echo "  ✘ нет $SH"; exit 1; }

mk_services() {
    cat > "$WORK/services.env" <<'EOS'
MODE=parallel
LAYER2=1
LAYER3=1
AZ_SUBNET=10.29.9
VPN_SUBNET=10.28.9
AZ3_SUBNET=10.29.10
VPN3_SUBNET=10.28.10
EOS
}

mk_kresd() {  # mk_kresd <есть ли ванильные view: 1|0>
    : > "$WORK/kresd.conf"
    printf '%s\n' "-- knot resolver config" >> "$WORK/kresd.conf"
    if [ "$1" = 1 ]; then
        # дословно с сервера: сетевой адрес, шлюз внутри str2ip
        for n in "10.29.0.0/22 10.29.0.1" "10.29.4.0/22 10.29.4.1" "10.29.8.0/24 10.29.8.1" \
                 "10.28.0.0/22 10.28.0.1" "10.28.4.0/22 10.28.4.1" "10.28.8.0/24 10.28.8.1"; do
            set -- $n
            printf "\tview:addr('%s', policy.domains(policy.ANSWER({[kres.type.A] = {rdata = kres.str2ip('%s'), ttl = min_ttl}}), {todname(hostname())}))\n" \
                "$1" "$2" >> "$WORK/kresd.conf"
        done
    fi
    printf '%s\n' "-- end" >> "$WORK/kresd.conf"
}

run_view() {
    AWG_KRESD="$WORK/kresd.conf" AWG_SERVICES="$WORK/services.env" \
        bash "$SH" >"$WORK/out" 2>"$WORK/err"
}

# ═══════════════════════════════════════════════════════════════════════════
head_ "1. View добавляются в том же формате, что у ванили"
mk_services; mk_kresd 1
run_view; rc=$?
[ "$rc" = 0 ] && ok "прогон завершился нулём" || bad "код $rc" "$(cat "$WORK/err")"
miss=""
for s in 10.29.9 10.28.9 10.29.10 10.28.10; do
    grep -q "view:addr('$s.0/24'" "$WORK/kresd.conf" || miss="$miss $s"
done
[ -z "$miss" ] && ok "view появились у всех четырёх подсетей" \
    || bad "нет view для:$miss" "клиент, спросивший имя своего сервера, получит внешний адрес"
# Именно сетевой адрес, а не адрес шлюза: на форме с .1 всё и сломалось.
grep -q "view:addr('10.29.9.1/24'" "$WORK/kresd.conf" \
    && bad "записана форма с адресом шлюза" "ваниль такой не пишет, и доктор её не найдёт" \
    || ok "форма сетевая, как у ванили"
grep -q "str2ip('10.29.9.1')" "$WORK/kresd.conf" \
    && ok "а внутри str2ip — шлюз, тоже как у ванили" \
    || bad "в str2ip не адрес шлюза" "$(grep -o "str2ip('10.29.9[^']*')" "$WORK/kresd.conf" | head -1)"

# ═══════════════════════════════════════════════════════════════════════════
head_ "2. Повторный прогон ничего не меняет"
cp "$WORK/kresd.conf" "$WORK/kresd.before"
run_view; rc=$?
[ "$rc" = 0 ] && ok "код нулевой" || bad "код $rc" "$(cat "$WORK/err")"
cmp -s "$WORK/kresd.before" "$WORK/kresd.conf" \
    && ok "файл не изменился" \
    || bad "второй прогон переписал файл" "view задвоятся при каждом обновлении"
grep -q 'ok' "$WORK/out" && ok "и сказано, что делать нечего" || true

# ═══════════════════════════════════════════════════════════════════════════
head_ "3. Некуда вставить — это слышно, а не тихий ноль"
# Ровно тот случай, что прожил незамеченным: якоря нет, вставлять некуда.
# Прежняя редакция возвращала ноль и молчала.
mk_services; mk_kresd 0
run_view; rc=$?
[ "$rc" != 0 ] && ok "код возврата $rc" \
    || bad "молча вышел с нулём" "вызывающий решит, что DNS настроен"
[ -s "$WORK/err" ] && ok "и сказано вслух" || bad "ни строки в stderr" "$(cat "$WORK/out")"

# ═══════════════════════════════════════════════════════════════════════════
head_ "4. Доктор ищет ту же форму, что пишет скрипт"
# Они меряли разными линейками: скрипт писал '10.29.9.1/24', доктор искал его же,
# но ваниль пишет сетевой адрес — и жалоба не могла погаснуть никогда.
DOC="$(grep -n "view:addr" overlay/bin/awg-doctor.sh || true)"
case "$DOC" in
    *"view:addr('\$s.0/24'"*) ok "доктор ищет сетевую форму" ;;
    *"view:addr('\$s.1/24'"*) bad "доктор ищет форму с адресом шлюза" \
        "такой строки не пишет ни ваниль, ни мы — замечание будет гореть всегда" ;;
    *) bad "не нашли проверку view в докторе" "$DOC" ;;
esac

# ═══════════════════════════════════════════════════════════════════════════
head_ "5. Вызовы в интеграции больше не глушат отказ"
CALLS="$(grep -n 'awg-knot-view.sh"' patches/antizapret-awg-integration.sh | grep -v '^\s*#' || true)"
n_mute="$(printf '%s\n' "$CALLS" | grep -c '2>/dev/null || true' || true)"
[ "$n_mute" = 0 ] \
    && ok "ни один вызов не проглатывает отказ" \
    || bad "вызовов с глушилкой: $n_mute" "шаг настройки снова сможет тихо не сработать"

printf '\n'
[ "$fail" = 0 ] && echo "═══ ВСЁ ЗЕЛЁНОЕ ═══" || echo "═══ ЕСТЬ ПАДЕНИЯ ═══"
exit "$fail"
