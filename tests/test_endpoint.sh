#!/bin/bash
# SPDX-License-Identifier: GPL-3.0-or-later
# Адрес сервера: где его сверять можно, а где проверка обязана молчать.
#
# Два измерения разной доказуемости, и мешать их нельзя:
#
#   M1  в Endpoint вообще есть разбираемый хост — доказывается ОДНИМ файлом,
#       ложных срабатываний нет вовсе, поэтому bad;
#   M2  хост у клиентов совпадает с объявленным — доказывается ДВУМЯ файлами
#       на диске, законные расхождения бывают, причина неизвестна → warn.
#
# Плюс отдельно: откуда берётся сам адрес. Объявленный WIREGUARD_HOST не
# оспаривается никогда — 192.168.1.10 у домашнего сервера в своей же локалке
# законен. А вот приватный адрес, который скрипт УГАДАЛ через `ip route get`
# за NAT, уезжает прямо в Endpoint и делает конфиг мёртвым, называясь созданным.
#
#   bash tests/test_endpoint.sh
fail=0
ROOT="$(cd "$(dirname "$(readlink -f "$0")")/.." && pwd)"
cd "$ROOT" || exit 1

ok()  { printf '  ✔ %s\n' "$1"; }
bad() { printf '  ✘ %s\n' "$1"; [ $# -gt 1 ] && printf '     %s\n' "$2"; fail=1; }
head_() { printf '\n\033[1m%s\033[0m\n' "$1"; }

WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

DOC=overlay/bin/awg-doctor.sh
CL=overlay/bin/client-awg.sh
HOSTFN="$(sed -n '/^ep_host()/,/^}$/p;/^norm_host()/p;/^check_client_hosts()/,/^}$/p' "$DOC")"
[ -n "$HOSTFN" ] || { bad "не нашли check_client_hosts в $DOC" "мерить нечего"; echo; exit 1; }

mk() {  # mk <каталог> <хост1> [хост2 …]
    local d="$1"; shift
    rm -rf "$d"; mkdir -p "$d"
    local i=0 h
    for h in "$@"; do
        i=$((i + 1))
        printf '[Interface]\nPrivateKey = K%s\n\n[Peer]\nEndpoint = %s\n' "$i" "$h" \
            > "$d/antizapret-c$i-am.conf"
    done
}

hosts() {  # hosts <объявленный> <каталог> → вывод проверки
    ( ok()   { printf 'OK %s\n' "$1"; }
      bad()  { printf 'BAD %s\n' "$1"; }
      warn() { printf 'WARN %s\n' "$1"; }
      eval "$HOSTFN"
      check_client_hosts "$1" "$2" antizapret-awg )
}

# ═══════════════════════════════════════════════════════════════════════════
head_ "1. Все конфиги на объявленном адресе — ни одной жалобы"
mk "$WORK/a" vpn.example.org:51820 vpn.example.org:51820 vpn.example.org:51820
out="$(hosts vpn.example.org "$WORK/a")"
case "$out" in
    *BAD*|*WARN*) bad "исправное состояние названо расхождением" "$out" ;;
    *) ok "проверка молчит по существу" ;;
esac
case "$out" in
    *"у всех 3 конфигов Endpoint на vpn.example.org"*) ok "и сказано, сколько проверено" ;;
    *) bad "число проверенных не названо" "$out" ;;
esac

# ═══════════════════════════════════════════════════════════════════════════
head_ "2. Часть конфигов выдана на другой адрес — так выглядит переезд"
# В AZ это состояние возникает само: новые клиенты берут адрес из живого
# /root/antizapret/setup новой машины, а восстановленные несут старый. В одном
# каталоге оказываются конфиги с разными хостами, и до сих пор об этом не
# говорилось нигде: check_ports сверяет у Endpoint только порт.
mk "$WORK/b" vpn.example.org:51820 203.0.113.7:51820 vpn.example.org:51820 203.0.113.7:51820
out="$(hosts vpn.example.org "$WORK/b")"
case "$out" in
    *"2 из 4 конфигов выданы на другой адрес"*) ok "посчитаны только несовпавшие" ;;
    *) bad "расхождение не посчитано" "$out" ;;
esac
case "$out" in *"203.0.113.7"*) ok "и показан образец" ;; *) bad "образец не показан" "$out" ;; esac
case "$out" in
    *"regen-all адрес не меняет"*) ok "и сказано, что regen-all тут не поможет" ;;
    *) bad "подсказка неверная или её нет" "regen-all правит только строки обфускации" ;;
esac
case "$out" in
    *BAD*) bad "расхождение названо поломкой" "после законной смены хоста это норма" ;;
    *) ok "это замечание, а не поломка" ;;
esac

# ═══════════════════════════════════════════════════════════════════════════
head_ "3. Endpoint без адреса — вот это поломка"
mk "$WORK/c" vpn.example.org:51820 :51820
out="$(hosts vpn.example.org "$WORK/c")"
case "$out" in
    *"BAD"*"нет адреса сервера"*) ok "конфиг без хоста назван поломкой" ;;
    *) bad "битый Endpoint пропущен" "$out" ;;
esac

# ═══════════════════════════════════════════════════════════════════════════
head_ "4. Объявленного адреса нет — сравнивать не с чем, и это не повод ворчать"
# В AZ так и бывает: ваниль без домена не задаёт WIREGUARD_HOST.
mk "$WORK/d" 203.0.113.7:51820 198.51.100.9:51820
out="$(hosts "" "$WORK/d")"
case "$out" in
    *WARN*|*BAD*) bad "жалоба при отсутствии объявленного адреса" "$out" ;;
    *) ok "проверка молчит" ;;
esac

# ═══════════════════════════════════════════════════════════════════════════
head_ "5. Регистр, точка FQDN и скобки — не расхождение"
mk "$WORK/e" VPN.Example.ORG:51820 vpn.example.org.:51820
out="$(hosts vpn.example.org "$WORK/e")"
case "$out" in
    *WARN*) bad "регистр или точка приняты за другой адрес" "$out" ;;
    *) ok "нормализация работает" ;;
esac

# ═══════════════════════════════════════════════════════════════════════════
head_ "6. Хост берётся до ПОСЛЕДНЕГО двоеточия, а не до первого"
mk "$WORK/f" '[2001:db8::1]:51820'
out="$(hosts '2001:db8::1' "$WORK/f")"
case "$out" in
    *WARN*|*BAD*) bad "адрес в скобках разобран неверно" "$out" ;;
    *) ok "адрес в скобках разбирается целиком" ;;
esac

# ═══════════════════════════════════════════════════════════════════════════
head_ "7. Угаданный приватный адрес не должен уехать в Endpoint"
SH="$(sed -n '/^server_host()/,/^}$/p' "$CL")"
if [ -z "$SH" ]; then
    bad "не нашли server_host в $CL" "мерить нечего"
else
    S="$WORK/stub"; mkdir -p "$S"
    printf '#!/bin/sh\necho "1.1.1.1 via 10.0.0.1 dev eth0 src 10.0.0.5"\n' > "$S/ip"
    printf '#!/bin/sh\necho 203.0.113.7\n' > "$S/curl"
    chmod +x "$S/ip" "$S/curl"
    got="$( PATH="$S:$PATH"; eval "$SH"; server_host )"
    case "$got" in
        10.0.0.5) bad "в Endpoint уехал приватный адрес 10.0.0.5" \
                      "за NAT такой конфиг мёртв, а выглядит созданным" ;;
        203.0.113.7) ok "приватный src отброшен, взят внешний адрес" ;;
        *) bad "неожиданный адрес: [$got]" ;;
    esac

    # А ОБЪЯВЛЕННЫЙ приватный адрес оспаривать нельзя: домашний сервер в своей
    # же локалке — законный случай, и подмена его на внешний всё бы сломала.
    mkdir -p "$WORK/az"
    printf 'WIREGUARD_HOST=192.168.1.10\n' > "$WORK/az/setup"
    got="$( PATH="$S:$PATH"
            SH2="${SH//\/root\/antizapret\/setup/$WORK\/az\/setup}"
            eval "$SH2"; server_host )"
    case "$got" in
        192.168.1.10) ok "объявленный приватный адрес оставлен как есть" ;;
        *) bad "объявленный адрес подменён на [$got]" \
               "домашний сервер в своей локалке — законный случай" ;;
    esac
fi

printf '\n'
[ "$fail" = 0 ] && echo "═══ ВСЁ ЗЕЛЁНОЕ ═══" || echo "═══ ЕСТЬ ПАДЕНИЯ ═══"
exit $fail
